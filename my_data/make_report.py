"""Build my_data/metrics_overview.html from my_data/results/<dataset>.csv"""
import json, sys, pandas as pd, os
here = os.path.dirname(os.path.abspath(__file__))
ds = sys.argv[1] if len(sys.argv) > 1 else 'citylearn_challenge_2023_phase_3_1'
df = pd.read_csv(f'{here}/results/{ds}.csv', index_col=0)
CATS = [
 ("Cost & energy", "What the district pays, emits and draws from the grid.", [
  ("cost_total","Electricity bill","Total money spent on grid electricity."),
  ("carbon_emissions_total","Carbon emissions","CO2 from the electricity drawn, using the hourly carbon intensity."),
  ("electricity_consumption_total","Energy drawn","Total net kWh taken from the grid."),
  ("zero_net_energy","Zero net energy","Net kWh consumed minus kWh generated by PV. Lower means closer to self-sufficient.")]),
 ("Grid stress", "How spiky and jumpy the combined demand is. Utilities care about this.", [
  ("all_time_peak_average","All-time peak","Highest single-hour demand over the whole period."),
  ("daily_peak_average","Daily peak","Average of each day's highest-demand hour."),
  ("ramping_average","Ramping","Sum of hour-to-hour changes in demand. High means a jumpy load."),
  ("daily_one_minus_load_factor_average","Daily 1 - load factor","1 minus (average demand / peak demand) per day. 0 is a perfectly flat day."),
  ("monthly_one_minus_load_factor_average","Monthly 1 - load factor","Same idea over a month.")]),
 ("Comfort", "How often and how far indoor temperature leaves the comfort band. Only counted when occupied.", [
  ("discomfort_proportion","Uncomfortable hours","Share of occupied hours outside the comfort band (too hot + too cold)."),
  ("discomfort_hot_proportion","Too hot hours","Share of occupied hours that are too hot."),
  ("discomfort_cold_proportion","Too cold hours","Share of occupied hours that are too cold."),
  ("discomfort_hot_delta_average","Hot: average overshoot (°C)","When too hot, the average degrees above the band. Raw °C, not normalized."),
  ("discomfort_hot_delta_maximum","Hot: worst overshoot (°C)","Largest degrees above the band. Raw °C."),
  ("discomfort_hot_delta_minimum","Hot: smallest overshoot (°C)","Smallest degrees above the band. Raw °C."),
  ("discomfort_cold_delta_average","Cold: average undershoot (°C)","When too cold, the average degrees below the band. Raw °C."),
  ("discomfort_cold_delta_maximum","Cold: worst undershoot (°C)","Largest degrees below the band. Raw °C."),
  ("discomfort_cold_delta_minimum","Cold: smallest undershoot (°C)","Smallest degrees below the band. Raw °C.")]),
 ("Resilience", "How the district copes with power outages and unmet demand.", [
  ("one_minus_thermal_resilience_proportion","Uncomfortable during outages","Share of outage hours where the building is uncomfortable."),
  ("power_outage_normalized_unserved_energy_total","Unmet demand in outages","Share of demand not served during outages."),
  ("annual_normalized_unserved_energy_total","Unmet demand overall","Share of all demand not served.")]),
]
cols = list(df.columns)
cats = []
for name, blurb, ms in CATS:
    rows = []
    for key, title, desc in ms:
        rows.append(dict(key=key, title=title, desc=desc, vals=[float(df.loc[key, c]) for c in cols]))
    cats.append(dict(name=name, blurb=blurb, rows=rows))
missing = set(df.index) - {k for _, _, ms in CATS for k, _, _ in ms}
assert not missing, missing
data = dict(dataset=ds, controllers=cols, cats=cats)
html = open(f'{here}/metrics_template.html').read().replace('/*DATA*/null', json.dumps(data))
open(f'{here}/metrics_overview.html', 'w').write(html)
print('wrote', f'{here}/metrics_overview.html')
