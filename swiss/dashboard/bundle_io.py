"""Bundle file format: JSON wrapped in one JS assignment so index.html can load it from file:// with <script>.

Line 1: a comment. Line 2: `(window.SCL=window.SCL||{})["<name>"]=`. Line 3..: the JSON. Last char: `;`.
"""
import json

HEADER = '/* generated by swiss/dashboard/build_bundle.py - do not edit; JSON payload starts on line 3 */\n'


def write_bundle_file(path, name, obj, indent=None):
    payload = json.dumps(obj, ensure_ascii=False, separators=(',', ':') if indent is None else None, indent=indent,
                         allow_nan=False)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(HEADER)
        f.write(f'(window.SCL=window.SCL||{{}})["{name}"]=\n')
        f.write(payload)
        f.write(';\n')


def read_bundle_file(path):
    with open(path, encoding='utf-8') as f:
        text = f.read()
    _, _, rest = text.partition('\n')
    _, _, payload = rest.partition('\n')
    return json.loads(payload.rstrip().rstrip(';'))
