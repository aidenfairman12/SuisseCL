"""Heat peaks and load-duration curves per building and for the district (thermostat reference, heating-only cells).

For each climate cell (observed 2023 'hist', '+2.0 C' and '+3.0 C' typical years, no cooling) the thermostat reference is rolled out over the full year in CityLearn
(the same rollout as the 'thermostat_year' task of climate_matrix.py) and, per building and summed over the district, the hourly series are taken from the environment:
  heat_el   space-heating heat-pump electricity (kWh per hour = kW)   this is the heating electricity of climate_summary.json
  heat_th   heat delivered to the room (kWh_th per hour = kW_th)     the model's heating_demand
Per series: annual energy, peak hourly value, full-load hours (annual / peak) and a load-duration curve (values sorted from high to low, sampled at N_POINTS ranks).
The district series is the hourly sum over the six buildings, so its peak is the coincident peak (not the sum of the building peaks).
All series are modeled: composite district, RC building model, synthetic heat timing (see docs/phases/phase_c_completion_report.md for the limits).

Run:  PYTHONPATH=. cl/bin/python swiss/experiments/heat_peaks.py run      (about 2 minutes per cell)   |   report   (markdown from the JSON)
Output: swiss/experiments/heat_peak_results/heat_peaks.json, docs/experiments/validation_reports/heat_peaks.md
"""
import argparse
import json
import os
import sys
import warnings

import numpy as np

warnings.filterwarnings('ignore')
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
RES = os.path.join(ROOT, 'swiss', 'experiments', 'heat_peak_results')
OUT = os.path.join(RES, 'heat_peaks.json')
REPORT = os.path.join(ROOT, 'docs', 'experiments', 'validation_reports', 'heat_peaks.md')
CELLS = ('hist_none', 'gwl2.0_none', 'gwl3.0_none')
N_POINTS = 150
KINDS = ('heat_el', 'heat_th')


def stats(x, hours=None):
    """Annual energy, peak, full-load hours and the sampled load-duration curve of one hourly series (kWh per hour)."""
    x = np.asarray(x, dtype=float)
    ann, peak = float(x.sum()), float(x.max())
    srt = np.sort(x)[::-1]
    rank = np.unique(np.round(np.linspace(0, len(x) - 1, N_POINTS)).astype(int))     # includes rank 0 (the peak) and the last hour
    return {'annual_kwh': ann, 'peak_kw': peak, 'full_load_hours': ann / peak if peak > 0 else None, 'hours': int(len(x)),
            'ldc': {'rank_hour': rank.tolist(), 'kw': np.round(srt[rank], 3).tolist()}}


def run_cell(cell):
    from swiss.experiments import climate_controllers as cc, climate_matrix as cm, oracle_climate as oc
    cm.ensure_datasets([cell])
    inp = oc.ClimateInputs(cell)
    env = cm.rollout_year(inp, lambda e: cc.ThermostatAgentCool(e))
    n = min(len(b.heating_electricity_consumption) for b in env.buildings)
    series = {r: {'heat_el': np.asarray(b.heating_electricity_consumption, dtype=float)[:n], 'heat_th': np.asarray(b.heating_demand, dtype=float)[:n]} for r, b in zip(inp.roles, env.buildings)}
    series['district'] = {k: np.sum([series[r][k] for r in inp.roles], axis=0) for k in KINDS}
    return {k: {kind: stats(v[kind]) for kind in KINDS} for k, v in series.items()}, list(inp.roles)


def run():
    os.makedirs(RES, exist_ok=True)
    out = {'cells': {}, 'n_points': N_POINTS, 'controller': 'thermostat', 'source': 'swiss/experiments/heat_peaks.py (thermostat full-year rollout of the heating-only climate cells)'}
    for c in CELLS:
        out['cells'][c], roles = run_cell(c)
        out['roles'] = roles
        print(c, 'district peak', out['cells'][c]['district']['heat_el']['peak_kw'], 'annual', out['cells'][c]['district']['heat_el']['annual_kwh'], flush=True)
    with open(OUT, 'w') as f:
        json.dump(out, f)


def change_pct(a, b):
    return 100.0 * (b - a) / a


def table(d, roles, kind, warm):
    """Rows per building and district: annual MWh, peak kW, full-load hours for hist and the warm cell, and the percentage changes."""
    rows = []
    for r in roles + ['district']:
        h, w = d['cells']['hist_none'][r][kind], d['cells'][warm][r][kind]
        rows.append({'role': r, 'annual_mwh': [h['annual_kwh'] / 1e3, w['annual_kwh'] / 1e3], 'peak_kw': [h['peak_kw'], w['peak_kw']], 'flh': [h['full_load_hours'], w['full_load_hours']],
                     'annual_change_pct': change_pct(h['annual_kwh'], w['annual_kwh']), 'peak_change_pct': change_pct(h['peak_kw'], w['peak_kw'])})
    return rows


def report():
    d = json.load(open(OUT))
    roles = d['roles']
    L = ['# Heat peaks and load-duration curves (thermostat reference, heating-only cells)', '',
         'Generated by `swiss/experiments/heat_peaks.py report`. Modeled values: composite district, RC building model, synthetic heat timing. Peak = highest hourly value of the year (kW = kWh per hour); '
         'full-load hours = annual energy / peak. The district peak is the coincident peak of the six buildings.', '']
    for kind, name in (('heat_el', 'heating electricity (heat-pump input)'), ('heat_th', 'heat delivered to the rooms')):
        for warm in ('gwl2.0_none', 'gwl3.0_none'):
            L += [f'## {name}: observed 2023 vs {warm.split("_")[0].replace("gwl", "+")} C', '',
                  '| Building | Annual MWh (2023 / warm) | Change | Peak kW (2023 / warm) | Change | Full-load hours (2023 / warm) |', '|---|---|---|---|---|---|']
            for r in table(d, roles, kind, warm):
                L.append(f'| {r["role"]} | {r["annual_mwh"][0]:.1f} / {r["annual_mwh"][1]:.1f} | {r["annual_change_pct"]:+.1f} % | {r["peak_kw"][0]:.1f} / {r["peak_kw"][1]:.1f} | {r["peak_change_pct"]:+.1f} % | {r["flh"][0]:.0f} / {r["flh"][1]:.0f} |')
            L.append('')
    cap_file = os.path.join(RES, 'heat_cap_check.json')
    if os.path.exists(cap_file):
        cap = json.load(open(cap_file))['cells']
        L += ['## Heat-pump capacity cap (swiss/experiments/heat_cap_check.py)', '',
              'The thermostat asks for the heat that holds the set point; the space-heating heat pump delivers at most its rated power (1.1 x the highest hourly space-heating electricity of the derived 2023 dataset). '
              'Buildings with hours at the cap show a peak equal to the rating; unmet heat is the requested heat the device could not deliver.', '',
              '| Building | Rated kW | Hours at cap (2023 / +2.0 / +3.0) | Hours below set point | K h below set point | Hours below comfort lower bound | Unmet heat kWh_th |', '|---|---|---|---|---|---|---|']
        cells = list(cap)
        for r in d['roles']:
            v = [cap[c][r] for c in cells]
            L.append(f'| {r} | {v[0]["rated_kw"]:.2f} | ' + ' / '.join(str(x['hours_at_cap']) for x in v) + ' | ' + ' / '.join(str(x['hours_below_setpoint']) for x in v) + ' | '
                     + ' / '.join(f'{x["kh_below_setpoint"]:.2f}' for x in v) + ' | ' + ' / '.join(str(x['hours_below_comfort_lower']) for x in v) + ' | ' + ' / '.join(f'{x["unmet_heat_kwh_th"]:.1f}' for x in v) + ' |')
        L += ['', 'Where a building sits at its cap, its peak equals the rating in every climate, so its peak change is 0.0 % (an uncapped heat pump would show a larger peak and a larger fall); the district peak may be slightly understated in the cap hours. '
              'The cap hours fall with warming; the room temperature never goes below the comfort lower bound. Sizing is unchanged by this analysis (assumption on device sizes: see the assumptions log).', '']
    with open(REPORT, 'w') as f:
        f.write('\n'.join(L) + '\n')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('cmd', choices=['run', 'report'])
    a = ap.parse_args()
    run() if a.cmd == 'run' else report()
