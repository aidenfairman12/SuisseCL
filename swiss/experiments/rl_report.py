"""Aggregate the Phase B RL results (D-044): learners x scenarios, mean and spread over seeds, next to the baselines and the exact optimum on the same test weeks.
Run: PYTHONPATH=. cl/bin/python swiss/experiments/rl_report.py       Output: docs/experiments/validation_reports/rl_phase_b.md and swiss/experiments/rl_results/phase_b_summary.json
Missing runs are listed as pending; nothing is invented."""
import glob
import json
import os
import sys

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
RES = os.path.join(ROOT, 'swiss', 'experiments', 'rl_results')
OUT = os.path.join(ROOT, 'docs', 'experiments', 'validation_reports', 'rl_phase_b.md')
KINDS = ('sac_central', 'sac_decentral', 'marlisa')
SC = {'s1': 'S1 (assumed PV)', 's2': 'S2 (+ battery)', 's3': 'S3 (+ RC thermal model, comfort)'}
KEYS = [('cost_chf_vs_zero_pct', 'bill raw'), ('cost_corrected_vs_zero_pct', 'bill corrected'), ('import_kwh_vs_zero_pct', 'import'), ('highest_hour_kw_vs_zero_pct', 'highest hour')]


def main():
    summary, L = {}, ['# Phase B RL results (held-out weeks, reward bill)', '',
                      'Generated by `swiss/experiments/rl_report.py`. Percentages are changes against the scenario reference on the same eight test weeks (zero action in S1 and S2, thermostat in S3); negative bill = saving. '
                      '"Corrected" credits stored heat, battery energy and building heat at the avoided electricity. Reference optimum = the year-long exact optimum evaluated on the same weeks (perfect foresight: an upper reference).', '']
    ref = json.load(open(os.path.join(ROOT, 'swiss', 'experiments', 'oracle_results', 'rl_reference.json')))['scenarios'] if os.path.exists(os.path.join(ROOT, 'swiss', 'experiments', 'oracle_results', 'rl_reference.json')) else {}
    for sc, label in SC.items():
        L += [f'## {label}', '']
        if sc in ref:
            L.append(f'Exact optimum on the test weeks: saves {ref[sc]["saving_pct"]:.2f} % of the {ref[sc]["zero_bill_test_chf"]:.0f} CHF reference bill (year: {ref[sc]["year_saving_pct"]:.2f} %).')
            L.append('')
        bp = os.path.join(RES, f'baselines_{sc}_weeks_bill.json')
        L += ['| Controller | n seeds | ' + ' | '.join(k[1] for k in KEYS) + ' | comfort K·h below 21 C |', '|---|---|' + '---|' * (len(KEYS) + 1)]
        if os.path.exists(bp):
            b = json.load(open(bp))
            for name, v in b.items():
                z = v['vs_zero']
                L.append(f'| {name} | - | ' + ' | '.join(f'{z[k[0]]:+.2f} %' for k in KEYS) + f' | {v["aggregate"]["comfort_cold_kh"]:.1f} |')
        for kind in KINDS:
            runs = sorted(glob.glob(os.path.join(RES, f'{sc}_{kind}_bill_weeks_s*', 'eval_final.json')))
            if not runs:
                L.append(f'| {kind} | 0 | pending (no finished run) | | | | |')
                continue
            fin = [json.load(open(r)) for r in runs]
            row = {}
            for key, name in KEYS:
                vals = np.array([f['vs_zero'][key] for f in fin])
                row[name] = f'{vals.mean():+.2f} ± {vals.std():.2f} %'
            comfort = np.mean([f['aggregate']['comfort_cold_kh'] for f in fin])
            L.append(f'| {kind} | {len(fin)} | ' + ' | '.join(row[k[1]] for k in KEYS) + f' | {comfort:.1f} |')
            summary[f'{sc}_{kind}'] = {'n': len(fin), **{k[1]: [f['vs_zero'][k[0]] for f in fin] for k in KEYS}, 'steps_trained': [f['steps_trained'] for f in fin]}
        L.append('')
    L += ['Notes: the learners start from random exploration; a learner that does not beat the zero-action reference shows a positive bill change. Seeds differ in network initialisation, exploration and the training windows drawn.', '']
    open(OUT, 'w', encoding='utf-8').write('\n'.join(L))
    json.dump(summary, open(os.path.join(RES, 'phase_b_summary.json'), 'w'), indent=1)
    print('\n'.join(L))


if __name__ == '__main__':
    main()
