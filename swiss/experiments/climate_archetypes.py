"""Comparison of the two cooling archetypes (WP2b): A central (whole building cooled, WP3) against B room units (cooled fraction f of the floor area, WP2b).

Reads swiss/experiments/climate_results/climate_summary.json (archetype A) and swiss/experiments/climate_results_ru/climate_summary_ru.json (archetype B); writes the generated
report docs/experiments/validation_reports/climate_archetypes.md. Nothing is typed by hand. Run: PYTHONPATH=. cl/bin/python swiss/experiments/climate_archetypes.py

Reading rules stated in the report: cooling energy per cooled building differs between the archetypes BY CONSTRUCTION (B cools a fraction of the floor area with proportional
capacity, A cools all of it); neither archetype is validated against Swiss field data; the cooled fraction 0.4 is an assumption without a source."""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
A = os.path.join(ROOT, 'swiss', 'experiments', 'climate_results', 'climate_summary.json')
B = os.path.join(ROOT, 'swiss', 'experiments', 'climate_results_ru', 'climate_summary_ru.json')
OUT = os.path.join(ROOT, 'docs', 'experiments', 'validation_reports', 'climate_archetypes.md')
SCENARIOS = ('hist', 'hist_hw99', 'gwl2.0', 'gwl2.0_hw99', 'gwl3.0', 'gwl3.0_hw99')
ADOPTION = ('low', 'medium', 'high')


def f1(x, nd=1):
    return '-' if x is None else f'{x:.{nd}f}'


def pct(x, nd=0):
    return '-' if x is None else f'{100 * x:.{nd}f} %'


def pv_cover(rec, key, prio='default'):
    """PV, battery and grid share of the cooling electricity (year, kWh-weighted over buildings) of a cell for the thermostat or optimum rollout."""
    a = rec[key][prio]['buildings']
    cool = sum(a[b]['annual']['cool'] for b in a)
    if cool <= 1e-9:
        return None, None, None, cool
    w = lambda k: sum((a[b]['annual'][k] or 0.0) * a[b]['annual']['cool'] for b in a) / cool   # noqa: E731
    return w('pv_share_of_cooling'), w('battery_share_of_cooling'), w('grid_share_of_cooling'), cool


def zones(rec):
    z = rec['degree_hours_above_26'].get('zones')
    return z


def share(rec, ctrl):
    c = rec['controllers'].get(ctrl)
    return None if not c else c.get('share_of_ceiling')


def row(cell, rec):
    th = pv_cover(rec, 'thermostat_year'); op = pv_cover(rec, 'optimum_year')
    return {'cell': cell, 'ceiling': rec['ceiling_year_pct'], 'mass': rec['mass_value_pts'], 'cool_th': rec['cooling_kwh']['baseline'], 'cool_op': rec['cooling_kwh']['optimum'],
            'pv_th': th[0], 'pv_op': op[0], 'summer_peak_th': rec['peak_kw']['summer_baseline'], 'summer_peak_op': rec['peak_kw']['summer_optimum'],
            'mpc': share(rec, 'mpc'), 'mpc_peak': share(rec, 'mpc_peak0.1'), 'pv_rule': share(rec, 'pv_rule'), 'dh': rec['degree_hours_above_26']['baseline'], 'zones': zones(rec)}


def main():
    a, b = json.load(open(A))['cells'], json.load(open(B))['cells']
    L = ['# Cooling archetypes: A central against B room units (Phase C, WP2b)', '',
         'Generated by `swiss/experiments/climate_archetypes.py` from `swiss/experiments/climate_results/climate_summary.json` (archetype A) and '
         '`swiss/experiments/climate_results_ru/climate_summary_ru.json` (archetype B). Nothing here is typed by hand.', '',
         '**Reading rules.** (1) Archetype A cools the whole cooled building to 26 C (one thermal node, central or ducted equivalent, WP2). Archetype B (room units, split or portable) '
         'cools only a fraction f of the floor area of the cooled building (default f = 0.4, assumption A-058 without a source; sensitivity 0.2 and 0.6); the rest floats; the two zones '
         'are independent thermal nodes with the same per-m2 parameters (no heat exchange between them, assumption), heating is one action split by area, and the cooling capacity is '
         'proportional to f. **Cooling energy per cooled building therefore differs between the archetypes by construction**, not as a finding. (2) Neither archetype is validated '
         'against Swiss field data of cooling energy; both are modelled. (3) The heating-only district (adoption none) is the same in both archetypes. (4) Degree-hours above 26 C: '
         '"building" = area-weighted sum of the zone values (f x cooled zone + (1 - f) x uncooled zone); the zone columns are raw K h summed over the room-unit buildings; a cooled zone '
         'is held at or below 26 C by the thermostat, so its value is the overshoot of the controller, not of the building; the overheating of uncooled floor area is a model artefact '
         'of the unshaded single-node room (ISS-046) and is an indicator, not a prediction. (5) Shares of the ceiling are on the eight held-out weeks (week 29 holds the heat wave '
         'in the `*_hw99` scenarios), MPC = weather-conditioned forecasts with weather taken as known (A-028).', '']
    L += ['## 1. Archetype A against B (f = 0.4), per climate scenario and adoption level', '',
          '| Scenario | Adoption (cooled building) | Arch. | Ceiling year | Mass value (pts) | Cooling el. thermostat / optimum (kWh) | PV share of cooling thermostat / optimum | Summer peak kW thermostat / optimum | PV rule share | MPC share | MPC peak 0.1 share | Degree-hours > 26 C (district, thermostat) |',
          '|---|---|---|---|---|---|---|---|---|---|---|---|']
    for sc in SCENARIOS:
        for ad in ADOPTION:
            ca, cb = f'{sc}_{ad}', f'{sc}_{ad}_ru'
            for arch, cell, src in (('A', ca, a), ('B', cb, b)):
                rec = src.get(cell)
                if rec is None:
                    continue
                r = row(cell, rec)
                L.append(f'| {sc} | {ad} ({", ".join(rec["cooled"])}) | {arch} | {f1(r["ceiling"], 2)} % | {f1(r["mass"], 2)} | {f1(r["cool_th"], 0)} / {f1(r["cool_op"], 0)} | '
                         f'{pct(r["pv_th"])} / {pct(r["pv_op"])} | {f1(r["summer_peak_th"])} / {f1(r["summer_peak_op"])} | {pct(r["pv_rule"])} | {pct(r["mpc"])} | {pct(r["mpc_peak"])} | {f1(r["dh"], 0)} |')
    L += ['', '## 2. Degree-hours above 26 C by zone (archetype B, thermostat reference, year)', '',
          '| Cell | Cooled zone (K h) | Uncooled zone of the cooled building (K h) | Building, area-weighted (K h) | Same building in archetype A (K h) |', '|---|---|---|---|---|']
    for sc in SCENARIOS:
        for ad in ADOPTION:
            rb = b.get(f'{sc}_{ad}_ru'); ra = a.get(f'{sc}_{ad}')
            if not rb or not ra:
                continue
            z = zones(rb)
            role = rb['cooled'][0]
            hb = rb['thermostat_year']['default']['buildings'][role].get('degree_hours_above')
            ha = ra['thermostat_year']['default']['buildings'][role].get('degree_hours_above')
            L.append(f'| {sc}_{ad}_ru | {f1(z["cooled_zone"]["baseline"] if z else None, 0)} | {f1(z["uncooled_zone"]["baseline"] if z else None, 0)} | {f1(hb, 0)} | {f1(ha, 0)} |')
    L += ['', '## 3. Cooled fraction sensitivity (gwl3.0_hw99, high adoption: MFH-large cooled)', '',
          '| Cooled fraction | Ceiling year | Mass value (pts) | Cooling el. thermostat / optimum (kWh) | PV share of cooling thermostat / optimum | Summer peak kW thermostat / optimum | MPC share | Degree-hours > 26 C (district, thermostat) |', '|---|---|---|---|---|---|---|---|']
    for lab, cell, src in (('0.2 (B)', 'gwl3.0_hw99_high_ru0.2', b), ('0.4 (B, default)', 'gwl3.0_hw99_high_ru', b), ('0.6 (B)', 'gwl3.0_hw99_high_ru0.6', b), ('1.0 (A, central)', 'gwl3.0_hw99_high', a)):
        rec = src.get(cell)
        if not rec:
            continue
        r = row(cell, rec)
        L.append(f'| {lab} | {f1(r["ceiling"], 2)} % | {f1(r["mass"], 2)} | {f1(r["cool_th"], 0)} / {f1(r["cool_op"], 0)} | {pct(r["pv_th"])} / {pct(r["pv_op"])} | '
                 f'{f1(r["summer_peak_th"])} / {f1(r["summer_peak_op"])} | {pct(r["mpc"])} | {f1(r["dh"], 0)} |')
    L += ['', '## 4. Difference method against the heating-only district (year optimum, added consumption)', '',
          '| Scenario | Adoption | Arch. | Added cooling el. (kWh) | Heating el. change (kWh) | Annual import change (kWh) | Annual export change (kWh) | Summer peak change (kW) |', '|---|---|---|---|---|---|---|---|']
    for sc in SCENARIOS:
        for ad in ADOPTION:
            for arch, cell, src in (('A', f'{sc}_{ad}', a), ('B', f'{sc}_{ad}_ru', b)):
                rec = src.get(cell)
                d = rec.get('difference_vs_none', {}).get('optimum') if rec else None
                if not d:
                    continue
                L.append(f'| {sc} | {ad} | {arch} | {f1(d["cool_kwh"], 0)} | {f1(d["heat_kwh"], 0)} | {f1(d["import_kwh"], 0)} | {f1(d["export_kwh"], 0)} | {f1(d["summer_peak_kw"])} |')
    L += ['', '## Limits', '- Archetype B is a two-zone idealisation: no heat exchange between the zones, heating split by area, units sized in proportion to the cooled area, no schedule (units run '
          'whenever the cooled zone would exceed 26 C), no dehumidification. Real room units are used in selected rooms and hours; the model cools a share of the area all the time it needs it.',
          '- Cooled fraction, set point (26 C), device efficiency and the 15 C cut-off are assumptions (A-040 to A-047, A-058 onward); no Swiss source was found for set points or room-level use.',
          '- Everything else (household load synthetic ISS-040, unsourced tanks ISS-032, known weather A-028, one station, delta-change climate) is as in `climate_matrix.md`.', '']
    open(OUT, 'w', encoding='utf-8').write('\n'.join(L))
    print('written', OUT)


if __name__ == '__main__':
    main()
