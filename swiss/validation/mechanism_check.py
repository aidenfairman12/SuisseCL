"""Mechanism check (spec section 5.1): which explanations of the controller results does the Phase A model actually support?

Reads the exact decomposition in web/public/bundle/sim/comparisons_year.json (written by swiss/contract/export_v1.py), the independent
results table (swiss/experiments/results/baselines_2023.csv) and the sensitivity table, and writes
docs/experiments/validation_reports/mechanism_check_phase_a.md. Every number in the report is computed here from those files; the wording
only states what the accounting identities show. Run: cl/bin/python -I swiss/validation/mechanism_check.py
"""
import json
import os

import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
COMP = os.path.join(ROOT, 'web', 'public', 'bundle', 'sim', 'comparisons_year.json')
RES = os.path.join(ROOT, 'swiss', 'experiments', 'results', 'baselines_2023.csv')
SENS = os.path.join(ROOT, 'swiss', 'experiments', 'results', 'sensitivity_2023.csv')
OUT = os.path.join(ROOT, 'docs', 'experiments', 'validation_reports', 'mechanism_check_phase_a.md')
UI = os.path.join(ROOT, 'swiss', 'dashboard', 'ui_map.yaml')
REF = 'ALG-001_zero_action'
SENS_NAMES = {'basic_rbc': 'night-charging rule', 'tariff_rbc_r0.10': 'tariff-timed rule (medium)'}


def names():
    import yaml
    with open(UI, encoding='utf-8') as f:
        c = yaml.safe_load(f)['_controllers']
    return {k: v['display_name'] for k, v in c.items()}


def build():
    comp = json.load(open(COMP, encoding='utf-8'))
    res = pd.read_csv(RES).set_index('controller')
    sens = pd.read_csv(SENS)
    nm = names()
    rows = {k: v for k, v in comp['comparisons'].items() if k != 'ALG-002_business_as_usual'}
    n = lambda x, d=0: f'{x:,.{d}f}'.replace(',', ' ')  # noqa: E731  (space as thousands separator; never touches prose punctuation)
    f = lambda x, d=1: f'{x:+,.{d}f}'.replace(',', ' ')  # noqa: E731
    out = ['# Mechanism check, Phase A (annual 2023, district totals)', '',
           'Generated by `swiss/validation/mechanism_check.py` from `web/public/bundle/sim/comparisons_year.json` (exact accounting identities, '
           'tested in `swiss/tests/test_contract.py`) and `swiss/experiments/results/baselines_2023.csv`. Nothing here is typed in by hand. '
           'Reference = "No control". "Business as usual" is identical to it in this district and is omitted.', '',
           '## 1. What each rule changes (district totals, full year)', '',
           '| Controller | Import | Highest hour | Mean daily peak | Cost | Carbon (relative) | High-tariff share | Moved out of high tariff |',
           '|---|---|---|---|---|---|---|---|']
    for k, c in rows.items():
        m, x = c['metrics'], c['mechanisms']
        out.append(f"| {nm[k]} | {f(m['import_kwh_el']['delta_pct'], 2)} % | {f(m['peak_kw_el']['delta_pct'], 2)} % | {f(m['mean_daily_peak_kw_el']['delta_pct'], 2)} % | "
                   f"{f(m['cost_chf']['delta_pct'], 2)} % | {f(x['relative_carbon_change_pct'], 2)} % | {f(100 * m['high_tariff_import_share']['delta'], 1)} points | "
                   f"{n(x['import_moved_out_of_high_tariff_kwh_el'])} kWh_el |")
    out += ['', 'Reference values: ' + f"import {n(res.loc[REF, 'district_import_kwh'])} kWh_el, highest hour {res.loc[REF, 'district_peak_kw']:.1f} kW_el, "
            f"mean daily peak {res.loc[REF, 'mean_daily_peak_kw']:.1f} kW_el, cost {n(res.loc[REF, 'cost_chf_excl_vat'])} CHF excl. VAT, "
            f"high-tariff share {100 * res.loc[REF, 'high_tariff_import_share']:.1f} %.", '',
            '## 2. Where the extra electricity comes from (exact decomposition)', '',
            'The controller changes only the heat that passes through the tanks (heat pump to tank, tank to demand); the demand is fixed. '
            'So the extra heat-pump electricity is exactly: **heat lost in the tanks** (converted at the charging COP) + **heat still stored at the '
            'end of the year** + **COP timing** (charging when it is colder than when the heat is used, or the reverse).', '',
            '| Controller | Extra electricity | from tank losses | from stored remainder | from COP timing | Tank heat in / out (kWh_th) | Loss share of heat in |',
            '|---|---|---|---|---|---|---|']
    for k, c in rows.items():
        x = c['mechanisms']
        out.append(f"| {nm[k]} | {n(x['extra_hp_electricity_kwh_el'])} kWh_el | {n(x['electricity_from_tank_losses_kwh_el'])} | {n(x['electricity_from_stored_remainder_kwh_el'])} | "
                   f"{n(x['electricity_from_cop_timing_kwh_el'])} | {n(x['tank_heat_in_kwh_th'])} / {n(x['tank_heat_out_kwh_th'])} | "
                   f"{100 * x['extra_tank_loss_kwh_th'] / x['tank_heat_in_kwh_th']:.1f} % |")
    out += ['', '## 3. Cost and carbon', '',
            'Cost change = **tariff timing** (charging in cheaper hours than the hours in which the stored heat would otherwise have been produced) + '
            '**extra electricity bought** at the charging price. Carbon is the same identity with the modeled carbon series, in percent of the reference, '
            '**relative only** (ISS-033, D-013b).', '',
            '| Controller | Cost change | tariff timing | extra electricity | Carbon change | carbon timing | carbon extra electricity |',
            '|---|---|---|---|---|---|---|']
    for k, c in rows.items():
        x, m = c['mechanisms'], c['metrics']
        out.append(f"| {nm[k]} | {f(m['cost_chf']['delta'], 0)} CHF | {f(x['cost_from_tariff_timing_chf'], 0)} CHF | {f(x['cost_from_extra_electricity_chf'], 0)} CHF | "
                   f"{f(x['relative_carbon_change_pct'], 2)} % | {f(x['carbon_from_timing_pct'], 2)} % | {f(x['carbon_from_extra_electricity_pct'], 2)} % |")
    out += ['', '## 4. What the model supports, and what it does not', '', '**Supported by the accounting (given the assumptions in section 6):**']
    for k, c in rows.items():
        x, m = c['mechanisms'], c['metrics']
        saved = -x['cost_from_tariff_timing_chf']
        bought = x['cost_from_extra_electricity_chf']
        share = lambda key: 100 * x[key] / x['extra_hp_electricity_kwh_el']  # noqa: E731
        out.append(f"- *{nm[k]}*: cost {f(m['cost_chf']['delta'], 0)} CHF. Shifting to cheaper hours saved {n(saved)} CHF, but {n(x['extra_hp_electricity_kwh_el'])} kWh_el "
                   f"of extra electricity cost {n(bought)} CHF; {share('electricity_from_tank_losses_kwh_el'):.0f} % of that extra electricity "
                   f"is tank losses and {share('electricity_from_cop_timing_kwh_el'):.0f} % is COP timing."
                   + (' The tariff gain does **not** cover the extra electricity.' if m['cost_chf']['delta'] > 0 else ' The tariff gain covers the extra electricity.'))
    raises = [k for k, c in rows.items() if c['metrics']['peak_kw_el']['delta'] > 0]
    cheaper = [k for k, c in rows.items() if c['mechanisms']['carbon_from_timing_pct'] and c['mechanisms']['carbon_from_timing_pct'] > 0]
    out += ['', '**Not supported or only partly supported:**',
            f"- *Peak demand.* The highest single hour changes by {', '.join(f(rows[k]['metrics']['peak_kw_el']['delta_pct'], 1) + ' % (' + nm[k] + ')' for k in rows)}, "
            f"but the mean daily peak changes by only {', '.join(f(rows[k]['metrics']['mean_daily_peak_kw_el']['delta_pct'], 2) + ' %' for k in rows)}. "
            "A claim that a rule \"reduces peaks\" holds at most for the single annual maximum, not for typical days"
            + (f"; {', '.join(nm[k] for k in raises)} even raise{'s' if len(raises) == 1 else ''} the annual maximum." if raises else '.'),
            f"- *Carbon.* The carbon-timing term is positive for {len(cheaper)} of {len(rows)} rules" + (": the cheap hours are not the clean hours in the modeled series. " if len(cheaper) == len(rows) else ". ") +
            "The level of that series is 61-63 % of the EPFL reference (D-013b), so only the sign and rough size of relative changes may be quoted, never tonnes. "
            "Carbon reductions are not a finding of Phase A.",
            '- *Why the controller charges when it does* is a property of the rule (clock or tariff map), not something the simulation explains; the check covers accounting, not intent.',
            '- *Comfort and unmet heat* are not modeled; demand is always met, so no statement about comfort can be made.', '',
            '## 5. Two aggregations that must not be mixed', '',
            'The CityLearn KPI table (`kpi_*` columns) is the **unweighted mean of the six per-building ratios** (verified: the mean of the per-building carbon, cost and import ratios of '
            'the night-charging rule reproduces its KPI values to 1e-5, `test_per_building_kpi_average_differs_from_district_total`). The district totals above are energy-weighted. '
            'They answer different questions and differ in size (for the night-charging rule the carbon KPI is '
            f"{res.loc['ALG-003_basic_rbc', 'kpi_carbon_emissions_total']:.4f}, the district total {1 + rows['ALG-003_basic_rbc']['mechanisms']['relative_carbon_change_pct'] / 100:.4f}). "
            'Use district totals for district claims and label the KPI table as an average of building ratios.', '',
            '## 6. What these conclusions depend on', '',
            '- Tank sizes, efficiency (0.95) and standby loss (0.3 %/h) are **assumed** (D-017a, ISS-029, ISS-032). The tank-loss share above is a result of those assumptions.',
            '- Heat demand is derived from electricity and its timing is unvalidated (ISS-028, ISS-030); the COP form is a Carnot-fraction model (M-001).',
            '- One year (2023), one tariff (EKZ standard, excl. VAT), carbon modeled and relative only.']
    s = sens[sens.variant != 'reference']
    for ctrl, g in s.groupby('controller'):
        if ctrl == 'zero_action':
            continue
        out.append(f"- Sensitivity ({SENS_NAMES.get(ctrl, ctrl)}, {len(g)} variants, not including the base case): cost change {g.cost_vs_zero_pct.min():+.2f} % to {g.cost_vs_zero_pct.max():+.2f} %, "
                   f"peak {g.peak_vs_zero_pct.min():+.1f} % to {g.peak_vs_zero_pct.max():+.1f} % (`sensitivity_2023.csv`).")
    out.append('')
    return '\n'.join(out)


if __name__ == '__main__':
    text = build()
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print('wrote', os.path.relpath(OUT, ROOT), f'({len(text)} characters)')
